# ---------------------------------------------------------------- E1 diagnostics
diag = read("e1_diagnostics.csv")
DG = {}
for r in diag or []:
    DG[(r["part"], r["scenario"], r["setting"], r["metric"])] = float(r["value"])


def dg(key, fmt):
    return fmt(DG[key]) if key in DG else "\\pending"


for scen in ("DC", "D0", "D1", "D2"):
    S = WORD[scen]
    macro(f"EoneLayerFs{S}", dg(("a", scen, "layer scale", "median |R| at flooding surfaces"), lambda v: f"{v:.4f}"))
    macro(f"EoneLayerRef{S}", dg(("a", scen, "layer scale", "median |R| at reference horizons"), lambda v: f"{v:.4f}"))
    macro(f"EoneLayerPct{S}", dg(("a", scen, "layer scale", "flooding-surface percentile"), ordinal))
    new_key = ("a", scen, "layer scale", "mean reflection coefficient at flooding surfaces (seismic sign)")
    old_key = ("a", scen, "layer scale", "mean signed R at flooding surfaces")   # v3.4: upper minus lower
    if new_key not in DG and old_key in DG:
        DG[new_key] = -DG[old_key]
    macro(f"EoneLayerSign{S}", dg(new_key, lambda v: f"${v:+.4f}$"))
    kf, kr = (("a", scen, "layer scale", "median |R| at flooding surfaces"),
              ("a", scen, "layer scale", "median |R| at reference horizons"))
    macro(f"EoneLayerRatio{S}", f"{DG[kf] / DG[kr]:.1f}" if kf in DG and kr in DG and DG[kr] > 0 else "\\pending")
    for f0 in ("30", "60"):
        F = {"30": "Thirty", "60": "Sixty"}[f0]
        macro(f"EonePctStr{F}{S}", dg(("b", scen, f"{f0} Hz", "strength percentile"), ordinal))
        macro(f"EonePctCon{F}{S}", dg(("b", scen, f"{f0} Hz", "continuity percentile"), ordinal))
macro("EoneHiatus", dg(("a", "all", "layer scale", "fraction of flooding surfaces on a hiatus"), pct))
macro("EoneDeepening", dg(("a", "all", "layer scale", "water-depth change across flooding surfaces (m)"), lambda v: f"{v:.1f}"))
c_vals = [v for (p, s_, st, m), v in DG.items() if p == "c" and m == "strength percentile"]
macro("EoneProfileMin", ordinal(min(c_vals)) if c_vals else "\\pending")
macro("EoneProfileMax", ordinal(max(c_vals)) if c_vals else "\\pending")

