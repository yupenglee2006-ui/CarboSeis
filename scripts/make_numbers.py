"""Write tables/numbers.tex: LaTeX macros for every result quoted in the text.

The manuscript inputs this file, so the numbers in the prose always match the latest run.
A missing source table leaves its macros as a red RESULT PENDING marker.
"""
import csv
import json
from pathlib import Path

import numpy as np

from common import ROOT, TAB

OUT = TAB / "numbers.tex"
lines = ["% Generated by scripts/make_numbers.py -- do not edit by hand.",
         "\\providecommand{\\pending}[1][]{\\textcolor{red}{[RESULT PENDING#1]}}"]
WORD = {"D0": "Dzero", "D1": "Done", "D2": "Dtwo", "DC": "DC", "Level 1": "LI", "Level 2": "LII",
        "15.0": "Fifteen", "30.0": "Thirty", "60.0": "Sixty",
        "interior": "Interior", "margin": "Margin", "slope": "Slope", "basin": "Basin"}


def macro(name, value):
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def read(name):
    p = TAB / name
    if not p.exists():
        return None
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def pct(v):
    try:
        return f"{100 * float(v):.0f}"
    except (TypeError, ValueError):
        return "n/a"


def ordinal(v):
    """Percentile as an English ordinal, e.g. 0.62 -> 62nd."""
    try:
        n = int(round(100 * float(v)))
    except (TypeError, ValueError):
        return "n/a"
    suf = "th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suf}"


def num(v, nd=2):
    try:
        return f"{float(v):.{nd}f}"
    except (TypeError, ValueError):
        return "n/a"


